-- 1. Crea un bucket público llamado recuerdos (Storage > New bucket).
-- 2. Ejecuta este SQL en Supabase > SQL Editor.
create table if not exists public.recuerdos (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(nombre) <= 80),
  mensaje text default '' check (char_length(mensaje) <= 500),
  archivo_url text not null,
  archivo_nombre text not null,
  tipo text not null check (tipo in ('imagen','video')),
  created_at timestamptz not null default now()
);

alter table public.recuerdos enable row level security;

-- Los invitados pueden publicar recuerdos.
create policy "Cualquiera puede compartir recuerdos"
on public.recuerdos for insert
to anon, authenticated
with check (
  char_length(nombre) between 1 and 80
  and char_length(mensaje) <= 500
  and tipo in ('imagen','video')
);

-- La galería pública puede mostrar recuerdos.
create policy "Cualquiera puede ver recuerdos"
on public.recuerdos for select
to anon, authenticated
using (true);

-- Para el bucket Storage llamado recuerdos:
-- Permite subir archivos sin iniciar sesión.
create policy "Cualquiera puede subir archivos de boda"
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'recuerdos');

-- Permite que la galería muestre los archivos del bucket.
create policy "Cualquiera puede ver archivos de boda"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'recuerdos');
